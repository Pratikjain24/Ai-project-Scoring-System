export interface LiveMetric {
  id: string;
  label: string;
  value: number; // 0 to 100
  unit?: string;
  trend: 'up' | 'down' | 'stable';
  status: 'optimal' | 'good' | 'warning';
  subtext: string;
}

export interface LiveClaim {
  id: string;
  timestamp: string;
  text: string;
  category: 'performance' | 'originality' | 'hardware' | 'architecture';
  status: 'VERIFIED' | 'ANALYZING' | 'FLAGGED' | 'RESOLVED';
  evidenceRef: string;
  confidence: number;
}

export interface TranscriptEntry {
  id: string;
  timestamp: string;
  speaker: 'Presenter' | 'AI Juror Core' | 'Co-Presenter';
  text: string;
  isQuestion?: boolean;
}

export interface EvidenceItem {
  id: string;
  module: string;
  type: string;
  status: 'CONNECTED' | 'STREAMING' | 'VERIFYING' | 'SYNCHRONIZED';
  latency: string;
  detail: string;
}

